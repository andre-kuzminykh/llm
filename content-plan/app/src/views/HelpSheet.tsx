/** «Как пользоваться»: все подсказки в одном месте; раздел текущего экрана — первым. */
export function HelpSheet({ view, onClose }: { view: View; onClose: () => void }) {
  const cur = view === 'month' ? 'week' : view
  const list = [...TOPICS].sort((a, b) => Number(b.id === cur) - Number(a.id === cur))
  return (
    <aside className="cp-sheet" aria-label="Как пользоваться">
      <div className="cp-sheet__head">
        <h2 className="cp-sheet__title">Как пользоваться</h2>
        <IconButton icon="close" label="Закрыть" onClick={onClose} />
      </div>
      <div className="cp-sheet__body nr-scroll cp-help">
        {list.map((t) => (
          <section key={t.id} aria-label={t.title}>
            <h3>{t.title}</h3>
            {t.body}
          </section>
        ))}
      </div>
    </aside>
  )
}
